// Command ouigen converts the IEEE MA-L registry CSV into a Go lookup table
// (docs/DECISIONS.md D9). Run via `make oui` (go generate in internal/enrich).
package main

import (
	"bytes"
	"encoding/csv"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"slices"
	"strconv"
	"strings"
	"time"
)

const registryURL = "https://standards-oui.ieee.org/oui/oui.csv"

func main() {
	in := flag.String("in", "", "read the registry CSV from this file instead of downloading it")
	out := flag.String("out", "oui_table.go", "output Go file")
	pkg := flag.String("pkg", "enrich", "package name of the generated file")
	flag.Parse()

	src, err := open(*in)
	if err != nil {
		log.Fatal(err)
	}
	defer func() { _ = src.Close() }()

	entries, err := parse(src)
	if err != nil {
		log.Fatal(err)
	}
	code, err := render(*pkg, entries)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, code, 0o644); err != nil { //nolint:gosec // generated source file
		log.Fatal(err)
	}
	log.Printf("wrote %s: %d prefixes", *out, len(entries))
}

func open(path string) (io.ReadCloser, error) {
	if path != "" {
		return os.Open(path) //nolint:gosec // operator-supplied path
	}
	client := &http.Client{Timeout: 2 * time.Minute}
	req, err := http.NewRequest(http.MethodGet, registryURL, nil)
	if err != nil {
		return nil, err
	}
	req.Header.Set("User-Agent", "cybercity-ouigen")
	resp, err := client.Do(req)
	if err != nil {
		return nil, fmt.Errorf("download %s: %w", registryURL, err)
	}
	if resp.StatusCode != http.StatusOK {
		_ = resp.Body.Close()
		return nil, fmt.Errorf("download %s: %s", registryURL, resp.Status)
	}
	return resp.Body, nil
}

type entry struct {
	prefix uint32
	vendor string
}

func parse(r io.Reader) ([]entry, error) {
	rows, err := csv.NewReader(r).ReadAll()
	if err != nil {
		return nil, fmt.Errorf("parse csv: %w", err)
	}
	if len(rows) < 2 || rows[0][1] != "Assignment" || rows[0][2] != "Organization Name" {
		return nil, fmt.Errorf("unexpected registry header %v", rows[0])
	}
	byPrefix := map[uint32]string{}
	for _, row := range rows[1:] {
		if len(row) < 3 || row[0] != "MA-L" {
			continue
		}
		p, err := strconv.ParseUint(row[1], 16, 32)
		if err != nil || len(row[1]) != 6 {
			return nil, fmt.Errorf("bad assignment %q", row[1])
		}
		name := strings.Join(strings.Fields(row[2]), " ")
		if name == "" || name == "Private" {
			continue
		}
		byPrefix[uint32(p)] = name
	}
	entries := make([]entry, 0, len(byPrefix))
	for p, v := range byPrefix {
		entries = append(entries, entry{p, v})
	}
	slices.SortFunc(entries, func(a, b entry) int { return int(a.prefix) - int(b.prefix) })
	return entries, nil
}

// render writes three parallel tables: sorted prefixes, an index into a
// de-duplicated name list per prefix, and the names.
func render(pkg string, entries []entry) ([]byte, error) {
	var names []string
	nameIndex := map[string]int{}
	for _, e := range entries {
		if _, ok := nameIndex[e.vendor]; !ok {
			nameIndex[e.vendor] = len(names)
			names = append(names, e.vendor)
		}
	}
	if len(names) > 1<<16 {
		return nil, fmt.Errorf("%d vendor names exceed uint16 index", len(names))
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/ouigen from the IEEE MA-L registry; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	fmt.Fprintf(&b, "// %d prefixes, %d distinct vendor names.\n\n", len(entries), len(names))

	b.WriteString("var ouiPrefixes = [...]uint32{\n")
	for i, e := range entries {
		fmt.Fprintf(&b, "0x%06X,", e.prefix)
		if i%10 == 9 {
			b.WriteByte('\n')
		}
	}
	b.WriteString("\n}\n\nvar ouiVendorIndex = [...]uint16{\n")
	for i, e := range entries {
		fmt.Fprintf(&b, "%d,", nameIndex[e.vendor])
		if i%16 == 15 {
			b.WriteByte('\n')
		}
	}
	b.WriteString("\n}\n\nvar ouiVendorNames = [...]string{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "%q,\n", n)
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
